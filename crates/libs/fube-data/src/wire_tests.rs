fn hex(value: &str) -> Vec<u8> {
    value
        .split_whitespace()
        .map(|b| u8::from_str_radix(b, 16).unwrap())
        .collect()
}

// Only the common object envelope is assembled; the fields below are literal,
// independent native-source fixtures, not values generated by the codec tested.
fn native_object(fields: &[u8]) -> Vec<u8> {
    let mut bytes = vec![0];
    bytes.extend_from_slice(&((fields.len() + 11) as u32).to_le_bytes());
    bytes.extend_from_slice(&[0, 0, 0, 0, 0x1f]);
    bytes.extend_from_slice(fields);
    bytes.extend_from_slice(&[0x2f, 0x3f]);
    bytes
}

