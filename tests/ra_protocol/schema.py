def adapted(native_type):
    native_type = re.sub(r"\s+", " ", native_type.strip()).removeprefix("::")
    if native_type in ENUMS:
        return "Enum"
    if native_type in SCALARS:
        return SCALARS[native_type]
    match = re.fullmatch(r"(?:std::)?vector<\s*(.*?)\s*>", native_type)
    if match:
        item = "byte" if match[1] == "byte" else adapted(match[1])
        return f"std::vector<{item}>"
    simple = native_type.rsplit("::", 1)[-1]
    if simple == "NodeId" or simple in {item[0] for item in MODELS}:
        return simple
    raise ValueError(f"unmapped native field type: {native_type}")


def extract(native):
    result = []
    for name, path, base in MODELS:
        text = (native / "src/prod/src" / path).read_text()
        if base:
            if not re.search(rf"(?:class|struct)\s+{name}\s*:\s*public\s+(?:\w+::)*{base}\b", text):
                raise ValueError(f"{path}: native inheritance no longer matches {base}")
        kind = "FABRIC_PRIMITIVE_FIELDS" if base is None else "FABRIC_FIELDS"
        macros = list(re.finditer(rf"\b({kind}_(\d+))\s*\(([^)]*)\)", text, re.S))
        if len(macros) != 1:
            raise ValueError(f"{path}: expected exactly one field macro, got {len(macros)}")
        macro = macros[0]
        fields = [v.strip() for v in macro[3].split(",")]
        if int(macro[2]) != len(fields):
            raise ValueError(f"{path}: field count mismatch")
        declarations = []
        for field in fields:
            matches = sorted({t.strip() for t in re.findall(
                rf"^[ \t]*([\w:<>, \t]+?)\s+{field}\s*;", text, re.M
            ) if t.strip() != "return" and "<<" not in t})
            if len(matches) != 1:
                raise ValueError(f"{path}: expected one declaration of {field}: {matches}")
            declarations.append((field, matches[0].strip(), adapted(matches[0])))
        result.append((name, path, base, macro[1], declarations))
    return result


def generate(native, destination):
    models = extract(native)
    output = [
        "// Generated from pinned native headers; source macro/member provenance below.",
        "#pragma once", "#include <Serialization.h>", "#include <FabricSerializationHelper.h>",
        "enum class Enum : LONG { Zero = 0 };",
        "inline void rich(Enum& v,int& c) { v=Enum(++c%5); }",
        "struct NodeId { ULONG64 high_ = 0, low_ = 0; };",
        "inline void rich(NodeId& v,int& c) { ++c; for(size_t i=0;i<16;++i)reinterpret_cast<UCHAR*>(&v)[i]=(c+i)%256; }",
        "FABRIC_SERIALIZE_AS_BYTEARRAY(NodeId);",
        "inline bool same(NodeId a, NodeId b) { return a.high_ == b.high_ && a.low_ == b.low_; }",
        "inline bool same(const std::wstring& a, const std::wstring& b) {",
        " if(a.size()!=b.size())return false; for(size_t i=0;i<a.size();++i)if(a[i]!=b[i])return false; return true; }",
        "template<class T> bool same(const T& a, const T& b) { return a == b; }",
        "template<class T> bool same(const std::vector<T>& a, const std::vector<T>& b) {",
        " if(a.size()!=b.size())return false; for(size_t i=0;i<a.size();++i)if(!same(a[i],b[i]))return false; return true; }",
        "template<class T> bool same(const std::shared_ptr<T>& a,const std::shared_ptr<T>& b) {",
        " return (!a&&!b)||(a&&b&&a->matches(*b)); }",
    ]
    for name, path, base, macro, fields in models:
        inheritance = "" if base is None else f" : {base or 'Serialization::FabricSerializable'}"
        output += [f"// {path} (native field types retained in comments)", f"struct {name}{inheritance} {{"]
        for field, native_type, cpp in fields:
            default = DEFAULTS.get((name, field), "{}")
            output.append(f" {cpp} {field} = {default}; // {native_type}")
        if name == "TimeSpan":
            output.append(" static TimeSpan minimum() { TimeSpan t; t.ticks_ = INT64_MIN; return t; }")
        if name == "ReplicaDescription":
            output.append(
                " ReplicaDescription() { packageVersionInstance_.version_.appVersion_.value_.major_=0;"
                " packageVersionInstance_.version_.value_.major_=0; }"
            )
        if name in {"ScalingTrigger", "ScalingMechanism"}:
            output += [
                f" static Serialization::IFabricSerializable* FabricSerializerActivator(Serialization::FabricTypeInformation);",
                " NTSTATUS GetTypeInformation(Serialization::FabricTypeInformation& info) const override {",
                " info.buffer=reinterpret_cast<const UCHAR*>(&kind_); info.length=sizeof(kind_); return 0; }",
                f" virtual bool matches(const {name}& other) const {{ return kind_==other.kind_; }}",
            ]
        if base in {"ScalingTrigger", "ScalingMechanism"}:
            output += [
                f" bool matches(const {base}& other) const override {{",
                f" auto p=dynamic_cast<const {name}*>(&other); return p && *this==*p; }}",
            ]
        comparison = " && ".join(f"same({f}, other.{f})" for f, _, _ in fields)
        if base:
            comparison = f"same(static_cast<const {base}&>(*this), static_cast<const {base}&>(other)) && " + comparison
        output += [
            f" bool operator==(const {name}& other) const {{ return {comparison}; }}",
            f" {macro}({', '.join(f for f, _, _ in fields)});", "};",
        ]
        if name not in {"GuidValue", "TimeSpan", "ErrorCode"}:
            output.append(f"DEFINE_USER_ARRAY_UTILITY({name});")
    output += ['#include "scaling.inc"']
    # Rich fixture traversal follows native macro order, not declaration order.
    # Field values are supplied by fixture.cpp, independently of Rust.
    for name, _, base, _, fields in models:
        if name.startswith(("Scaling", "Average", "InstanceCount", "AddRemove")):
            continue
        output.append(f"inline void rich({name}& v, int& c) {{")
        if base:
            output.append(f" rich(static_cast<{base}&>(v), c);")
        for field, _, _ in fields:
            if name == "ServiceDescription" and field == "scalingPolicies_":
                output.append(f" rich_scaling(v.{field}, c);")
            else:
                output.append(f" rich(v.{field}, c);")
        output.append("}")
    destination.write_text("\n".join(output) + "\n")
    return models
